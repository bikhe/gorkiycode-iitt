"""Minimal interface for a Django CRUD adapter or local test storage."""
from __future__ import annotations
from typing import Protocol, Any

class CrudPort(Protocol):
    def create_item(self,user_id:str,data:dict,request_id:str)->dict:...
    def get_item(self,user_id:str,item_id:int)->dict|None:...
    def list_items(self,user_id:str,date_from:str,date_to:str,kind:str|None=None)->list[dict]:...
    def search_items(self,user_id:str,query:str)->list[dict]:...
    def update_item(self,user_id:str,item_id:int,changes:dict)->dict:...
    def delete_item(self,user_id:str,item_id:int)->bool:...
    def get_session(self,user_id:str,session_id:str)->dict:...
    def save_session(self,user_id:str,session_id:str,state:dict)->None:...

class PlannerPort(Protocol):
    def plan(self,text:str,context:dict,now:Any,catalog:list[dict])->dict:...
